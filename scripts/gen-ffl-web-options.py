#!/usr/bin/env python3
"""Writes webapp/lib/firebase_options.dart for the FFL Travel Buddy web app from the secrets
folder (never committed). The config comes from the Web app registered in Firebase project
gen-lang-client-0717949368 (saved by `firebase apps:sdkconfig WEB` into
../travelbuddy-secrets/ffl-web-config.json).

Run once after cloning, or after the Firebase config changes:
    python3 scripts/gen-ffl-web-options.py
"""
import json, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sec = os.path.join(os.path.dirname(root), "travelbuddy-secrets", "ffl-web-config.json")
try:
    web = json.load(open(sec))
except FileNotFoundError:
    sys.exit(f"Missing secret file: {sec}")

keys = ["apiKey", "appId", "messagingSenderId", "projectId", "authDomain", "storageBucket"]
missing = [k for k in keys if not web.get(k)]
if missing:
    sys.exit(f"ffl-web-config.json is missing: {missing}")

opts = "\n".join(f"    {k}: '{web[k]}'," for k in keys)
out = f"""// GENERATED by scripts/gen-ffl-web-options.py from ../travelbuddy-secrets — DO NOT COMMIT.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;

/// Firebase project of the FFL Travel Buddy Android app (gen-lang-client-0717949368).
const FirebaseOptions fflWebOptions = FirebaseOptions(
{opts}
);
"""
dst = os.path.join(root, "webapp", "lib", "firebase_options.dart")
open(dst, "w").write(out)
print("wrote", os.path.relpath(dst, root))
