#!/usr/bin/env python3
"""Writes client/lib/firebase_options.dart from the secrets folder (never committed).
Run once after cloning, or after the Firebase config changes:  python3 scripts/gen-firebase-options.py"""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sec = os.path.join(os.path.dirname(root), "travelbuddy-secrets")
try:
    gs = json.load(open(os.path.join(sec, "google-services.json")))
    web = json.load(open(os.path.join(sec, "firebase-web-config.json")))
except FileNotFoundError as e:
    sys.exit(f"Missing secret file: {e.filename}")
client = next(c for c in gs["client"] if c["client_info"]["android_client_info"]["package_name"] == "com.homilabs.travelbuddy")
pi = gs["project_info"]
# Google sign-in on Android (google_sign_in v7) needs the WEB client id as serverClientId.
web_client = next((c["client_id"] for c in client.get("oauth_client", []) if c["client_type"] == 3), web.get("apiKey") and "")
android = dict(apiKey=client["api_key"][0]["current_key"], appId=client["client_info"]["mobilesdk_app_id"],
               messagingSenderId=pi["project_number"], projectId=pi["project_id"], storageBucket=pi.get("storage_bucket", ""))
webo = dict(apiKey=web["apiKey"], appId=web["appId"], messagingSenderId=web["messagingSenderId"],
            projectId=web["projectId"], authDomain=web["authDomain"], storageBucket=web.get("storageBucket", ""))

def opts(d):
    return "\n".join(f"    {k}: '{v}'," for k, v in d.items())

out = f"""// GENERATED by scripts/gen-firebase-options.py from ../travelbuddy-secrets — DO NOT COMMIT.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart' show defaultTargetPlatform, kIsWeb, TargetPlatform;

/// Web OAuth client id, used as serverClientId for Google sign-in on Android.
const String googleServerClientId = '{web_client}';

class DefaultFirebaseOptions {{
  static FirebaseOptions get currentPlatform {{
    if (kIsWeb) return web;
    if (defaultTargetPlatform == TargetPlatform.android) return android;
    throw UnsupportedError('TravelBuddy runs on Android and web only.');
  }}

  static const FirebaseOptions android = FirebaseOptions(
{opts(android)}
  );

  static const FirebaseOptions web = FirebaseOptions(
{opts(webo)}
  );
}}
"""
dst = os.path.join(root, "client", "lib", "firebase_options.dart")
open(dst, "w").write(out)
print("wrote", os.path.relpath(dst, root))
